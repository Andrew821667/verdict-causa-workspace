class FactConsistencyCollector(BaseModel):
    """Собирает расхождения вместо того, чтобы падать на первом."""

    model_config = ConfigDict(extra="forbid")

    mismatches: list[FactConsistencyMismatch] = Field(default_factory=list)

    def equal(self, key: str, actual: bool, expected: bool) -> None:
        """Факт рецензента обязан совпасть с выводом модели."""
        if bool(actual) == bool(expected):
            return
        self._record(key, expected=bool(expected), actual=bool(actual))

    def implies(self, key: str, antecedent: bool, consequent: bool) -> None:
        """Из установленного факта обязан следовать другой факт."""
        if not antecedent or consequent:
            return
        self._record(key, expected=True, actual=False)

    def _record(self, key: str, expected: bool, actual: bool) -> None:
        if key not in FACT_CONSISTENCY_VOCABULARY:
            raise KeyError(f"Сверка {key!r} не описана по-русски в FACT_CONSISTENCY_VOCABULARY.")
        fact_ru, anchor_ru = FACT_CONSISTENCY_VOCABULARY[key]
        self.mismatches.append(
            FactConsistencyMismatch(
                key=key,
                fact_ru=fact_ru,
                anchor_ru=anchor_ru,
                expected=expected,
                actual=actual,
            )
        )

    def raise_if_any(self) -> None:
        if self.mismatches:
            raise FactConsistencyError(self.mismatches)
