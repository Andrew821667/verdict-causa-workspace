"""Сверка фактов рецензента с выводами модели: все расхождения одной ошибкой.

## Какой долг закрывает этот модуль

Один и тот же класс проблемы обрабатывался двумя несовместимыми способами.
Часть противоречий в данных рецензента отвергала анализ исключением на
английском языке и по одному за прогон; часть — называлась по-русски и
поднимала флаг экспертизы. Юрист видел либо объяснение, либо traceback, и от
чего это зависит, нигде не было записано.

## Принцип, по которому проходит граница

Он существовал, но не был сформулирован. Теперь сформулирован и закреплён
тестами.

**Отвергать** нужно там, где анализ иначе обязан молча выбрать одну из двух
версий факта. Заключённость договора выводится моделью статей 432–443, и она же
описана предикатом в данных о купле-продаже. Если значения разошлись, продолжить
можно, только предпочтя одно другому — а это и есть тот вред, ради устранения
которого строился слой сверки. Такие расхождения собирает этот модуль.

**Называть и поднимать флаг** нужно там, где обе версии могут ужиться в одном
анализе, не подменяя друг друга: недееспособность стороны в модели лиц и в
модели недействительности описывают разные институты, и решать, какая версия
верна, — работа рецензента, а не решателя. Такие расхождения обрабатывает
[`general_consistency`](general_consistency.py).

Разница не в тяжести противоречия, а в том, придётся ли решателю выбирать.

## Что изменилось по существу

Отвержение осталось отвержением: гарантии воспроизводимости не ослаблены, и
анализ по-прежнему не выдаёт результат на противоречивых данных. Изменилось
другое:

- расхождения собираются **все сразу**, а не по одному за прогон;
- сообщение написано **по-русски** и называет статью, из которой следует
  ожидаемое значение;
- ошибка **типизирована**: `FactConsistencyError` несёт разбор расхождений
  полями, а не только строкой;
- порядок проверок больше не влияет на то, о каком расхождении узнает
  пользователь.

Проверки воспроизводимости артефакта («does not replay from reviewed evidence»)
сюда не входят: они относятся не к фактам дела, а к целостности самого
артефакта, и остаются немедленными.
"""

from pydantic import BaseModel, ConfigDict, Field

FACT_CONSISTENCY_VERSION = "contracts-fact-consistency-v0"


class FactConsistencyMismatch(BaseModel):
    """Одно расхождение факта рецензента с выводом модели."""

    model_config = ConfigDict(extra="forbid", frozen=True)

    key: str
    fact_ru: str
    anchor_ru: str
    expected: bool
    actual: bool

    @property
    def line_ru(self) -> str:
        return (
            f"{self.fact_ru}: указано {_ru(self.actual)}, "
            f"а из вывода модели следует {_ru(self.expected)} — {self.anchor_ru}"
        )


def _ru(value: bool) -> str:
    return "«да»" if value else "«нет»"


class FactConsistencyError(ValueError):
    """Данные рецензента противоречат выводам модели.

    Несёт **все** расхождения, а не первое: исправлять их по одному за прогон
    было измеримо дороже, чем разом.
    """

    def __init__(self, mismatches: list[FactConsistencyMismatch]) -> None:
        self.mismatches = list(mismatches)
        lines = "\n".join(
            f"{number}. {mismatch.line_ru}."
            for number, mismatch in enumerate(self.mismatches, start=1)
        )
        super().__init__(
            "Данные рецензента противоречат выводам модели, поэтому анализ не выдан. "
            f"Расхождений: {len(self.mismatches)}.\n{lines}\n"
            "Приведите указанные факты в согласие с выводами моделей либо исправьте "
            "сами выводы, изменив факты, из которых они выведены. Слой не выбирает "
            "версию за рецензента."
        )

    @property
    def keys(self) -> list[str]:
        return [mismatch.key for mismatch in self.mismatches]


